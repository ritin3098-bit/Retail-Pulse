import sys
import os

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

import streamlit as st
from dashboard.utils import inject_theme, load_monitoring_data, missing_data_notice
from src.monitoring import split_reference_current, simulate_drift, quick_drift_check

st.set_page_config(page_title="Monitoring — RetailPulse", page_icon="🛰️", layout="wide")
inject_theme()

st.title("🛰️ Drift Monitoring")
st.caption(
    "Compares the statistical distribution of recent sales data against an "
    "earlier reference period. A drifted column suggests the model may need "
    "retraining."
)

clean = load_monitoring_data()
if clean is None:
    missing_data_notice("cleaned sales data", "python -m src.data_prep")
    st.stop()

reference, current = split_reference_current(clean)

mode = st.radio(
    "Check mode",
    ["Natural (real data, first half vs second half)", "Simulated drift (Price shifted ×1.6)"],
    help="Simulated mode artificially shifts a column to demonstrate the detector catching real drift.",
)

if "Simulated" in mode:
    current_checked = simulate_drift(current, column="Price", shift_factor=1.6)
    st.info("Price values in the 'current' window have been artificially multiplied by 1.6 for this demo.")
else:
    current_checked = current

result = quick_drift_check(reference, current_checked)

cols = st.columns(len(result))
for col, (_, row) in zip(cols, result.iterrows()):
    status = "🔴 Drift" if row["drift_detected"] else "🟢 Stable"
    col.metric(row["column"], status, delta=f"KS={row['ks_statistic']:.3f}")

st.dataframe(result, width="stretch")

n_drifted = result["drift_detected"].sum()
if n_drifted > 0:
    st.warning(
        f"{n_drifted} of {len(result)} monitored columns show statistically significant drift "
        f"(p < 0.05). In production, this would trigger the retraining pipeline (see `retrain.py`)."
    )
else:
    st.success("No significant drift detected in the monitored columns.")

st.divider()
st.caption(
    "A full Evidently AI HTML report (with per-feature distribution plots) can be "
    "generated by running `python -m src.monitoring` — saved to `reports/drift_report_natural.html` "
    "and `reports/drift_report_simulated.html`."
)
